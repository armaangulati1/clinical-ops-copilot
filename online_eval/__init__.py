"""Online evaluation loop: score live traffic on a schedule.

This package is deliberately *not* a second copy of the offline harness in
``evals/``. The two answer different questions:

* ``evals/`` scores a **fixed, labeled, held-out split at CI time**. It is a
  gate: the same 16 cases, the same labels, run before a merge.
* ``online_eval/`` samples **whatever traffic actually went through the agent**,
  scores it on a schedule, tracks the metrics as a time series, and compares the
  current window against a frozen baseline window to detect regression and
  drift. The population is not fixed and most of it is unlabeled.

Honest scope, stated once here and repeated in the README: this repository has
no deployed agent with real users. The traffic scored by this loop is
**simulated production traffic** generated by ``online_eval.simulated_traffic``
from the repo's own synthetic cases. Everything downstream of the trace store
(sampling, scoring, windowing, drift detection, alerting) is the same code that
would run against real traffic, but the traffic itself is generated, and no
claim of monitoring a production deployment is made anywhere in this package.

Import weight matters here. Everything from ``sampling`` through ``alerts``
depends only on pydantic plus this repo's metric modules, so an orchestrator
worker running the loop does not need the agent's model, MCP or FHIR
dependencies. Only ``simulated_traffic`` imports the agent, because only the
application emits traces.
"""

